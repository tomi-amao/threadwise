/**
 * Cash: can the business afford what it is about to do, and where did the money go?
 *
 * The first half answers the forward-looking questions (is trading paying for itself, how much is
 * safe to spend) over a trailing window ending today, so it does not move with the date filter.
 * The second half is the cash flow statement for the chosen period, with the check that it ties to
 * the bank, because a statement that does not tie back is unverifiable.
 */

import { useId } from 'react';
import { ResponsiveBar } from '@nivo/bar';
import { FilePdf } from 'phosphor-react';
import { ChartSummary, ChartTooltip, compactMoney, nivoTheme } from '~/components/charts';
import { Button, buttonVariants } from '~/components/ui/button';
import { Drawer } from '~/components/ui/drawer';
import { Meter } from '~/components/ui/meter';
import { Panel } from '~/components/ui/panel';
import { Statement, type StatementRow } from '~/components/ui/statement';
import { Term } from '~/components/ui/term';
import type { CashFlowLine, CashInsights, ReportsData } from '~/lib/api/reports.server';
import { cn } from '~/lib/utils';
import { int, money } from './model';

const VERDICT_TONE: Record<CashInsights['verdict'], string> = {
  generating: 'text-income',
  consuming: 'text-destructive',
  breakeven: 'text-accent-text',
  insufficient_data: 'text-text-2',
};

function CashHealth({ insights }: { insights: CashInsights }) {
  const stats: { label: React.ReactNode; value: string; tone?: 'good' | 'bad' }[] = [
    {
      label: (
        <Term definition="Average operating cash flow per complete month over the last 12 months. Leaves out the current partial month and director funding.">
          Average month
        </Term>
      ),
      value: money(insights.avgMonthlyOperating),
      tone: insights.avgMonthlyOperating >= 0 ? 'good' : 'bad',
    },
    {
      label: (
        <Term definition="Total operating cash generated or consumed over the last 12 complete months, before any funding.">
          Last 12 months
        </Term>
      ),
      value: money(insights.trailing12Operating),
      tone: insights.trailing12Operating >= 0 ? 'good' : 'bad',
    },
    ...(insights.bestMonth
      ? [
          {
            label: <>Best month ({insights.bestMonth.label})</>,
            value: money(insights.bestMonth.amount),
          },
        ]
      : []),
    ...(insights.worstMonth
      ? [
          {
            label: <>Worst month ({insights.worstMonth.label})</>,
            value: money(insights.worstMonth.amount),
          },
        ]
      : []),
  ];
  const pct = insights.selfFunding.pctFromTrading;

  return (
    <Panel
      title="Cash health"
      note={
        <Term definition="Based on operating cash flow over the last 6 complete months: money from trading only, before any funding you put in. Six months because release-driven months swing widely; one month would be noise. The month in progress is left out.">
          How trading is doing on its own
        </Term>
      }
    >
      <p className={cn('font-serif text-[26px]', VERDICT_TONE[insights.verdict])}>
        {insights.verdictHeadline}
      </p>
      <p className="mt-1.5 text-[14px] text-text-2">{insights.verdictDetail}</p>

      <dl className="mt-5 grid grid-cols-2 gap-x-6 gap-y-4 border-t pt-4">
        {stats.map((s, i) => (
          <div key={i}>
            <dt className="text-[13px] text-text-2">{s.label}</dt>
            <dd
              className={cn(
                'mt-0.5 tabular-nums',
                s.tone === 'good' && 'text-income',
                s.tone === 'bad' && 'text-destructive'
              )}
            >
              {s.value}
            </dd>
          </div>
        ))}
      </dl>

      {insights.runwayMonths !== null && (
        <p className="mt-4 rounded-xl border border-accent-text/30 bg-accent-tint px-3.5 py-2.5 text-[14px]">
          At the current average burn, cash on hand covers about{' '}
          <strong>{insights.runwayMonths} months</strong>. That assumes the trend carries on: a
          strong release month would reset it.
        </p>
      )}

      <div className="mt-5 border-t pt-4">
        <div className="text-[13px] text-text-2">
          <Term definition="Of all the cash that has come into the business, the share generated by trading rather than introduced by the director. 100% means the business has paid for itself entirely.">
            Funded by trading
          </Term>
        </div>
        {pct !== null ? (
          <>
            <div className="mt-2 flex items-center gap-3">
              <Meter
                value={pct / 100}
                label={`${pct}% of cash in came from trading`}
                className="flex-1"
              />
              <span className="tabular-nums">{pct}%</span>
            </div>
            <p className="mt-1.5 text-[13px] text-text-2">
              {money(insights.selfFunding.tradingCumulative)} from trading ·{' '}
              {money(insights.selfFunding.directorCumulative)} from you
              {insights.selfFunding.trailing12Covered
                ? ' · trading covered itself over the last 12 months'
                : ' · trading did not cover itself over the last 12 months'}
            </p>
          </>
        ) : (
          <p className="mt-1 text-[13px] text-text-2">Not enough activity to measure yet.</p>
        )}
      </div>
    </Panel>
  );
}

function SafeToSpend({ insights, onOpen }: { insights: CashInsights; onOpen: () => void }) {
  const share =
    insights.cashOnHand > 0 ? Math.max(0, insights.safeToSpend / insights.cashOnHand) : 0;
  return (
    <Panel
      title="Safe to spend"
      note={
        <Term
          align="end"
          definition="Cash in the bank, less the tax already accrued, any unpaid supplier bills, and a buffer the size of your worst trading month in the last year. What is left is what you could commit to a new release without relying on next month going well."
        >
          What you could commit today
        </Term>
      }
    >
      <div className="font-serif text-[40px] tabular-nums">{money(insights.safeToSpend)}</div>
      <p className="text-[13px] text-text-2">
        of {money(insights.cashOnHand)} in the bank ({Math.round(share * 100)}%)
      </p>
      <Meter
        value={share}
        label={`${Math.round(share * 100)}% of cash in the bank is safe to spend`}
        className="mt-3"
      />
      <ul className="mt-4 divide-y border-t text-[14px]">
        {insights.safeToSpendLines.slice(1).map(line => (
          <li key={line.label} className="flex items-baseline justify-between gap-3 py-2.5">
            <Term definition={line.detail} className="text-text-2">
              {line.label}
            </Term>
            <span className="tabular-nums">{money(line.amount)}</span>
          </li>
        ))}
      </ul>
      <Button variant="outline" size="sm" className="mt-4" onClick={onOpen}>
        See the full calculation
      </Button>
    </Panel>
  );
}

