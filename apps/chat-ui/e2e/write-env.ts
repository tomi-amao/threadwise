/**
 * Writes apps/chat-ui/.env.test from the running local Supabase stack.
 * Usage: pnpm e2e:env   (run `supabase start` first)
 */

import { execFileSync } from 'node:child_process';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { APP_DIR, ENV_FILE, REPO_ROOT, assertLocalSupabase } from './env';

const raw = execFileSync('supabase', ['status', '-o', 'env'], {
  cwd: REPO_ROOT,
  encoding: 'utf8',
  stdio: ['ignore', 'pipe', 'ignore'],
});

const status: Record<string, string> = {};
for (const line of raw.split('\n')) {
  const m = line.match(/^([A-Z0-9_]+)="(.*)"$/);
  if (m) status[m[1]] = m[2];
}

const url = assertLocalSupabase(status.API_URL);
if (!status.ANON_KEY || !status.SERVICE_ROLE_KEY) {
  throw new Error(
    '`supabase status` did not return ANON_KEY / SERVICE_ROLE_KEY. Is the stack running?'
  );
}

// Keep the throwaway test-user values from the example file (or an existing .env.test).
const source = [ENV_FILE, path.join(APP_DIR, '.env.test.example')].find(existsSync)!;
const existing: Record<string, string> = {};
for (const line of readFileSync(source, 'utf8').split('\n')) {
  const m = line.match(/^([A-Z0-9_]+)=(.*)$/);
  if (m) existing[m[1]] = m[2];
}

const out = {
  SUPABASE_URL: url,
  SUPABASE_ANON_KEY: status.ANON_KEY,
  SUPABASE_SERVICE_ROLE_KEY: status.SERVICE_ROLE_KEY,
  E2E_USER_EMAIL: existing.E2E_USER_EMAIL,
  E2E_USER_PASSWORD: existing.E2E_USER_PASSWORD,
};
writeFileSync(
  ENV_FILE,
  '# Generated by `pnpm e2e:env`. Local Supabase only. Gitignored.\n' +
    Object.entries(out)
      .map(([k, v]) => `${k}=${v}`)
      .join('\n') +
    '\n'
);
console.log(`Wrote ${path.relative(REPO_ROOT, ENV_FILE)} for ${url}`);
